#!/usr/bin/env bash
set -euo pipefail

# Commit of sunecz/Media-Downloader-Index whose schema the models follow
INDEXER_REF=551aded15b367bd90cf486315600dfbc67c24e1f
POSTGRES_IMAGE=postgres:18.7-alpine3.24
SQLACODEGEN=sqlacodegen==4.0.4
PSYCOPG='psycopg[binary]==3.3.9'
TABLES=dataset_meta,source,program
MIGRATION_PATH=app/core/src/main/resources/db/migration

usage() {
	printf 'Usage: %s [--migrations <dir>]\n' "$0"
}

MIGRATIONS=

while [ $# -gt 0 ]; do
	case "$1" in
		--migrations)
			MIGRATIONS=$(realpath "${2:?$(usage)}")
			shift 2
			;;
		*)
			usage
			exit 1
			;;
	esac
done

cd "$(dirname "$0")/.."

TMP=$(mktemp -d)
CONTAINER=

cleanup() {
	if [ -n "$CONTAINER" ]; then
		docker rm -f "$CONTAINER" >/dev/null
	fi

	rm -rf "$TMP"
}

trap cleanup EXIT

if [ -z "$MIGRATIONS" ]; then
	SOURCE="indexer $INDEXER_REF"
	MIGRATIONS="$TMP/migrations"
	mkdir -p "$MIGRATIONS"
	curl -fsSL "https://codeload.github.com/sunecz/Media-Downloader-Index/tar.gz/$INDEXER_REF" \
		| tar -xz -C "$MIGRATIONS" --strip-components=8 --wildcards "*/$MIGRATION_PATH/*"
else
	SOURCE="local migrations"
fi

mapfile -t FILES < <(
	find "$MIGRATIONS" -maxdepth 1 -name 'V*__*.sql' | sort -V
	find "$MIGRATIONS" -maxdepth 1 -name 'R__*.sql' | sort
)

if [ ${#FILES[@]} -eq 0 ]; then
	printf 'No migrations found in %s\n' "$MIGRATIONS"
	exit 1
fi

CONTAINER=$(docker run -d -e POSTGRES_USER=gen -e POSTGRES_PASSWORD=gen -e POSTGRES_DB=gen \
	-p 127.0.0.1::5432 "$POSTGRES_IMAGE")

# TCP only: the server of the image's initialization listens on the socket only
for _ in $(seq 60); do
	docker exec "$CONTAINER" pg_isready -q -h 127.0.0.1 -U gen -d gen && break
	sleep 1
done

for file in "${FILES[@]}"; do
	docker exec -i "$CONTAINER" psql -q -1 -v ON_ERROR_STOP=1 -U gen -d gen < "$file" >/dev/null
done

PORT=$(docker port "$CONTAINER" 5432/tcp | head -n 1 | sed 's/.*://')

uvx --python 3.15 --from "$SQLACODEGEN" --with "$PSYCOPG" sqlacodegen \
	--tables "$TABLES" \
	--options noindexes,nocomments \
	"postgresql+psycopg://gen:gen@127.0.0.1:$PORT/gen" > "$TMP/models.py"

{
	printf '# Generated by scripts/generate-models.sh (%s), do not edit\n' "$SOURCE"
	cat "$TMP/models.py"
} > app/db/models.py

printf 'Generated app/db/models.py from %s (%d migrations)\n' "$SOURCE" "${#FILES[@]}"
